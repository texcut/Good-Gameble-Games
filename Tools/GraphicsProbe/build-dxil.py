#!/usr/bin/env python3
"""Compile original SM 6.0 shaders into a checked-in C header. DXC is build-only."""
import argparse
import hashlib
import os
from pathlib import Path
import struct
import subprocess
import tempfile


def is_dxil(data):
    if len(data) < 32 or data[:4] != b"DXBC" or struct.unpack_from("<I", data, 24)[0] != len(data):
        return False
    count = struct.unpack_from("<I", data, 28)[0]
    if count > 32 or 32 + count * 4 > len(data):
        return False
    found = False
    for i in range(count):
        offset = struct.unpack_from("<I", data, 32 + i * 4)[0]
        if offset + 8 > len(data):
            return False
        length = struct.unpack_from("<I", data, offset + 4)[0]
        if offset + 8 + length > len(data):
            return False
        found |= data[offset:offset + 4] == b"DXIL"
    return found


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--dxc", required=True, type=Path)
    parser.add_argument("--wine", type=Path, help="Wine executable for the Windows DXC distribution")
    args = parser.parse_args()
    root = Path(__file__).resolve().parent
    source = root / "shaders/triangle.hlsl"
    compiler = args.dxc.resolve()
    environment = {k: v for k, v in os.environ.items() if not k.startswith("WINE")}
    with tempfile.TemporaryDirectory(prefix="GGGMac DXIL build ") as temporary:
        scratch = Path(temporary)
        prefix = scratch / "prefix"
        prefix.mkdir()
        if args.wine:
            environment.update(WINEPREFIX=str(prefix), WINEDEBUG="-all,err+all", MVK_CONFIG_LOG_LEVEL="2")
        def path(file):
            return "Z:" + str(file).replace("/", "\\") if args.wine else str(file)
        generated = ["/* SPDX-License-Identifier: GPL-3.0-or-later",
            " * Generated by build-dxil.py from original GGGMac triangle.hlsl.",
            " * Source SHA-256: " + hashlib.sha256(source.read_bytes()).hexdigest(),
            " * Rebuild instructions and compiler provenance: README.md.", " */"]
        try:
            for stage in ("vs", "ps"):
                target = scratch / (stage + ".dxil")
                command = ([str(args.wine.resolve())] if args.wine else []) + [str(compiler),
                    path(source), "-E", stage + "_main", "-T", stage + "_6_0", "-Fo", path(target),
                    "-Qstrip_debug", "-Qstrip_reflect", "-WX"]
                subprocess.run(command, env=environment, check=True, timeout=120)
                data = target.read_bytes()
                if not is_dxil(data):
                    raise RuntimeError("Compiler did not produce a valid DXIL container")
                generated.append("_Alignas(4) static const unsigned char gggmac_dxil_" + stage + "[] = {")
                for index in range(0, len(data), 16):
                    generated.append("    " + ", ".join("0x%02x" % byte for byte in data[index:index + 16]) + ",")
                generated.append("};")
                print(stage, len(data), "bytes; SHA-256", hashlib.sha256(data).hexdigest())
        finally:
            if args.wine:
                subprocess.run([str(args.wine.resolve().parent / "wineserver"), "-k"], env=environment, timeout=15, check=False)
        header = root / "shaders/triangle_dxil.h"
        staged = header.with_suffix(".tmp")
        staged.write_text("\n".join(generated) + "\n")
        staged.replace(header)


if __name__ == "__main__":
    main()
